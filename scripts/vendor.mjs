#!/usr/bin/env node
// ============================================================
// scripts/vendor.mjs: Self-host third-party files with SRI
// Usage:  npm run vendor        (needs internet access, Node ≥ 20)
//
// 1. Downloads each library listed in js/libs.js (from its pinned `cdn`
//    URL) into /vendor, computes a sha384 SRI hash, and rewrites
//    js/libs.js so `src` points at the local copy with `integrity` set.
// 2. Downloads the Google Fonts CSS + font files into /vendor/fonts and
//    writes css/fonts.css, then swaps the <!-- fonts:start/end --> block
//    in index.html for a link to it.
// 3. Removes the jsDelivr / Google Fonts hosts from the CSP in _headers.
//
// Safe to re-run (e.g. after bumping a version in js/libs.js `cdn`).
// Commit the resulting vendor/ folder and the rewritten files.
// ============================================================

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (...p) => path.join(root, ...p);

const FONTS_CSS_URL = process.env.FONTS_CSS_URL
  || 'https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,500..800&family=Instrument+Sans:wght@400..700&family=JetBrains+Mono:wght@400..700&display=swap';
// Google serves woff2 + unicode-range subsets only to modern browsers.
const MODERN_UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

async function download(url, headers = {}) {
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`${url} → HTTP ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

const sri = buf => 'sha384-' + createHash('sha384').update(buf).digest('base64');

// ── 1. Libraries ──────────────────────────────────────────

async function vendorLibs() {
  const { LIBS } = await import(pathToFileURL(rel('js', 'libs.js')).href + `?t=${Date.now()}`);
  await mkdir(rel('vendor'), { recursive: true });

  const out = {};
  for (const [name, lib] of Object.entries(LIBS)) {
    const file = path.posix.basename(new URL(lib.cdn).pathname);
    const buf = await download(lib.cdn);
    await writeFile(rel('vendor', file), buf);
    out[name] = { cdn: lib.cdn, src: `/vendor/${file}`, integrity: sri(buf), global: lib.global };
    console.log(`  ✓ ${name.padEnd(14)} ${(buf.length / 1024).toFixed(0).padStart(4)} KB  ${out[name].integrity.slice(0, 24)}…`);
  }

  const entries = Object.entries(out).map(([name, l]) => `  ${name}: {
    cdn:       '${l.cdn}',
    src:       '${l.src}',
    integrity: '${l.integrity}',
    global:    '${l.global}',
  },`).join('\n');

  const header = (await readFile(rel('js', 'libs.js'), 'utf8')).split('export const LIBS')[0];
  await writeFile(rel('js', 'libs.js'), `${header}export const LIBS = {\n${entries}\n};\n`);
}

// ── 2. Fonts ──────────────────────────────────────────────

async function vendorFonts() {
  let css = (await download(FONTS_CSS_URL, { 'User-Agent': MODERN_UA })).toString('utf8');
  const urls = [...new Set([...css.matchAll(/url\((https?:\/\/[^)]+)\)/g)].map(m => m[1]))];
  if (!urls.length) throw new Error('No font files found in the Google Fonts CSS');

  await mkdir(rel('vendor', 'fonts'), { recursive: true });
  for (const url of urls) {
    const name = createHash('sha1').update(url).digest('hex').slice(0, 12) + '.woff2';
    await writeFile(rel('vendor', 'fonts', name), await download(url));
    css = css.split(url).join(`/vendor/fonts/${name}`);
  }
  await writeFile(rel('css', 'fonts.css'), `/* Generated by scripts/vendor.mjs: self-hosted Google Fonts */\n${css}`);
  console.log(`  ✓ ${urls.length} font files → vendor/fonts, css/fonts.css`);

  // index.html: swap the marker block for the local stylesheet
  const htmlPath = rel('index.html');
  let html = await readFile(htmlPath, 'utf8');
  const block = /<!-- fonts:start[\s\S]*?<!-- fonts:end -->/;
  if (!block.test(html)) throw new Error('fonts:start / fonts:end markers not found in index.html');
  html = html.replace(block,
    '<!-- fonts:start (self-hosted by `npm run vendor`) -->\n  <link rel="stylesheet" href="/css/fonts.css">\n  <!-- fonts:end -->');
  await writeFile(htmlPath, html);

  // service worker precache must list every css file
  const swPath = rel('sw.js');
  let sw = await readFile(swPath, 'utf8');
  if (!sw.includes("'/css/fonts.css'")) {
    sw = sw.replace("    '/css/views.css',\n", "    '/css/views.css',\n    '/css/fonts.css',\n");
    await writeFile(swPath, sw);
  }
}

// ── 3. CSP ────────────────────────────────────────────────

async function tightenCsp() {
  const p = rel('_headers');
  let txt = await readFile(p, 'utf8');
  // replaceAll: these hosts appear in several directives (script-src, style-src,
  // font-src and connect-src, which the service worker's fetch() needs).
  for (const host of ['https://cdn.jsdelivr.net', 'https://fonts.googleapis.com', 'https://fonts.gstatic.com']) {
    txt = txt.replaceAll(` ${host}`, '');
  }
  await writeFile(p, txt);
  console.log('  ✓ _headers: jsDelivr and Google Fonts removed from the CSP');
}

console.log('Vendoring libraries…');
await vendorLibs();
console.log('Vendoring fonts…');
await vendorFonts();
console.log('Tightening CSP…');
await tightenCsp();
console.log('\nDone. Review `git diff`, run `npm test`, and commit vendor/.');
